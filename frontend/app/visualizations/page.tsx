'use client';

import React, { useEffect, useState } from 'react';
import Link from 'next/link';
import { BarChart3, Sparkles, Database } from 'lucide-react';
import { Header } from '@/components/header';
import { PlotlyChart } from '@/components/plotly-chart';
import { fetchVisualizations } from '@/lib/api';
import { VisualizationSpec } from '@/lib/types';

export default function VisualizationsPage() {
  const [charts, setCharts] = useState<VisualizationSpec[]>([]);
  const [isLoading, setIsLoading] = useState(true);

  useEffect(() => {
    async function load() {
      try {
        const data = await fetchVisualizations();
        setCharts(data);
      } finally {
        setIsLoading(false);
      }
    }
    load();
  }, []);

  return (
    <div className="flex-1 flex flex-col h-screen overflow-hidden">
      <Header
        title="Interactive Visualizations Gallery"
        description="Comprehensive collection of Plotly charts generated by the Visualization Agent."
        actionButton={
          <Link
            href="/analyst"
            className="flex items-center gap-1.5 px-3 py-1.5 bg-primary text-primary-foreground text-xs font-semibold rounded-lg hover:bg-primary/90 shadow-sm"
          >
            <Sparkles className="h-3.5 w-3.5" />
            <span>Generate New Chart</span>
          </Link>
        }
      />

      <div className="flex-1 overflow-y-auto p-8">
        {charts.length === 0 ? (
          <div className="p-12 text-center bg-card border border-dashed border-border rounded-xl text-xs text-muted-foreground flex flex-col items-center justify-center">
            <BarChart3 className="h-10 w-10 text-muted-foreground mb-3 opacity-30" />
            <h3 className="font-semibold text-foreground text-sm">No visualizations created yet</h3>
            <p className="max-w-sm mt-1 text-muted-foreground">
              Run analyses on your datasets to automatically generate and save Plotly charts here.
            </p>
          </div>
        ) : (
          <div className="grid grid-cols-2 gap-6">
            {charts.map((spec) => (
              <PlotlyChart key={spec.id} spec={spec} height={360} />
            ))}
          </div>
        )}
      </div>
    </div>
  );
}
